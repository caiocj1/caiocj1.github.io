#!/usr/bin/env python3
"""Render Obsidian Markdown notes into the existing static website."""
import argparse
from dataclasses import dataclass
from datetime import date
from html import escape
import os
from pathlib import Path
import re
from string import Template
from urllib.parse import quote, urlsplit, urlunsplit

import yaml
from markdown_it import MarkdownIt
from mdit_py_plugins.anchors import anchors_plugin
from mdit_py_plugins.dollarmath import dollarmath_plugin
from mdit_py_plugins.footnote import footnote_plugin

ROOT = Path(__file__).resolve().parents[1]
GENERATED = '<!-- Generated by scripts/build_notes.py; edit Markdown or templates instead. -->'
UNFRAMED_MATH_MARKER = '__CODEX_UNFRAMED_DISPLAY_MATH__'


@dataclass
class Note:
    source: Path
    title: str
    date: date
    description: str
    draft: bool
    body: str


def read_note(path):
    text = path.read_text(encoding='utf-8-sig')
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != '---':
        raise ValueError(f'{path}: add YAML properties at the top of the note.')
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == '---'), None)
    if end is None:
        raise ValueError(f'{path}: missing closing --- for properties.')
    data = yaml.safe_load(''.join(lines[1:end]))
    if not isinstance(data, dict):
        raise ValueError(f'{path}: properties must be a YAML mapping.')
    for field in ('title', 'description'):
        if not isinstance(data.get(field), str) or not data[field].strip():
            raise ValueError(f'{path}: {field} must be non-empty text.')
    note_date = data.get('date')
    if isinstance(note_date, str):
        try:
            note_date = date.fromisoformat(note_date)
        except ValueError:
            raise ValueError(f'{path}: date must use YYYY-MM-DD.') from None
    if type(note_date) is not date:
        raise ValueError(f'{path}: date must use YYYY-MM-DD.')
    draft = data.get('draft', True)
    if type(draft) is not bool:
        raise ValueError(f'{path}: draft must be true or false, without quotes.')
    return Note(path, data['title'], note_date, data['description'], draft,
                ''.join(lines[end + 1:]))


def normalize_display_math(body):
    """Give standalone $$ blocks Markdown boundaries without changing code fences."""
    lines = body.splitlines()
    normalized = []
    fence_marker = None
    in_display_math = False

    for line in lines:
        fence = re.match(r'^\s{0,3}(`{3,}|~{3,})', line)
        if fence:
            marker = fence.group(1)
            if fence_marker is None:
                fence_marker = (marker[0], len(marker))
            elif marker[0] == fence_marker[0] and len(marker) >= fence_marker[1]:
                fence_marker = None
            normalized.append(line)
            continue

        stripped = line.strip()
        plain_delimiter = stripped == '$$'
        labelled_closer = (in_display_math and
                            re.fullmatch(r'\$\$\s+\([^)$\r\n]+\)', stripped) is not None)
        if (fence_marker is None and not line.startswith(('    ', '\t')) and
                (plain_delimiter or labelled_closer)):
            if not in_display_math:
                has_blank_before = not normalized or not normalized[-1].strip()
                if not has_blank_before:
                    normalized.append('')
            normalized.append(line)
            if not in_display_math and not has_blank_before:
                normalized.append(UNFRAMED_MATH_MARKER)
            in_display_math = not in_display_math
            if not in_display_math:
                normalized.append('')
            continue

        normalized.append(line)

    return '\n'.join(normalized) + ('\n' if body.endswith('\n') else '')


def render_markdown(body):
    def math_source(content, options):
        unframed = options['display_mode'] and content.startswith(UNFRAMED_MATH_MARKER)
        if unframed:
            content = content[len(UNFRAMED_MATH_MARKER):].lstrip()
        left, right = ('\\[', '\\]') if options['display_mode'] else ('\\(', '\\)')
        marker = '<!-- unframed-display-math -->' if unframed else ''
        return marker + left + escape(content) + right

    md = (MarkdownIt('commonmark', {'html': False})
          .enable(['table', 'strikethrough'])
          .use(dollarmath_plugin, allow_labels=True, allow_space=False,
               allow_digits=False, renderer=math_source,
               label_renderer=lambda _: '')
          .use(footnote_plugin)
          .use(anchors_plugin, min_level=1, max_level=6))
    default_fence = md.renderer.rules['fence']

    def fenced_block(tokens, index, options, env):
        token = tokens[index]
        language = token.info.strip().split(maxsplit=1)[0].lower() if token.info.strip() else ''
        if language != 'mermaid':
            return default_fence(tokens, index, options, env)
        source = escape(token.content)
        return f'''<figure class="mermaid-figure">
<pre class="mermaid" role="img" aria-label="Mermaid diagram">{source}</pre>
<details class="mermaid-source">
<summary>Diagram source</summary>
<pre><code>{source}</code></pre>
</details>
</figure>
'''

    md.renderer.rules['fence'] = fenced_block
    tokens = md.parse(normalize_display_math(body))
    for token in tokens:
        # The template supplies the article title as h1.
        if token.type in ('heading_open', 'heading_close'):
            token.tag = f'h{min(int(token.tag[1]) + 1, 6)}'
        for child in token.children or []:
            if child.type == 'link_open':
                url = urlsplit(child.attrGet('href') or '')
                if not url.scheme and not url.netloc and url.path.endswith('.md'):
                    child.attrSet('href', urlunsplit(url._replace(path=url.path[:-3] + '.html')))
    html = md.renderer.render(tokens, md.options, {})
    html = re.sub(
        r'class="math block">(\s*)<!-- unframed-display-math -->',
        r'class="math block math-unframed">\1', html)
    # Tables retain their semantics while scrolling within a narrow viewport.
    return html.replace('<table>', '<div class="note-table" tabindex="0" role="group" aria-label="Table"><table>').replace('</table>', '</table></div>')


def date_label(value):
    return f'{value.day} {value.strftime("%B %Y")}'


def render_page(template, title, description, root, content, canonical, draft=False):
    metadata = '<meta name="robots" content="noindex, nofollow">' if draft else (
        f'<link rel="canonical" href="https://caiocj1.github.io/{quote(canonical)}">')
    page_scripts = ''
    if 'class="mermaid"' in content:
        page_scripts = f'''  <script defer src="{root}/assets/vendor/mermaid/mermaid.min.js"></script>
  <script defer src="{root}/assets/mermaid.js"></script>'''
    return template.substitute(title=escape(title), description=escape(description, quote=True),
                               root=root, content=content, page_metadata=metadata,
                               page_scripts=page_scripts)


def build(root=ROOT, include_drafts=False):
    root = Path(root)
    template = Template((root / 'templates/notes-page.html').read_text())
    notes = [read_note(path) for path in sorted((root / 'notes').rglob('*.md'))
             if not any(part.startswith('.') for part in path.relative_to(root / 'notes').parts)]
    notes = sorted((note for note in notes if include_drafts or not note.draft),
                   key=lambda note: (note.date, note.source.as_posix()), reverse=True)
    outputs = {}
    entries = []
    for note in notes:
        output = note.source.with_suffix('.html')
        site_root = Path(os.path.relpath(root, output.parent)).as_posix()
        url = output.relative_to(root).as_posix()
        label = '<span class="note-draft">Draft</span>' if note.draft else ''
        content = f'''  <main id="main-content" class="page-shell inner-page note-page">
    <article>
      <header class="page-intro note-intro">
        <a class="text-link math-back" href="{site_root}/notes.html">← Back to notes</a>
        <p class="note-meta"><time datetime="{note.date.isoformat()}">{date_label(note.date)}</time>{label}</p>
        <h1>{escape(note.title)}</h1>
        <p>{escape(note.description)}</p>
      </header>
      <div class="note-body">
{render_markdown(note.body)}
      </div>
    </article>
  </main>'''
        outputs[output] = render_page(template, note.title, note.description, site_root,
                                      content, url, note.draft)
        entries.append(f'''      <article class="note-list-item">
        <p class="note-meta"><time datetime="{note.date.isoformat()}">{date_label(note.date)}</time>{label}</p>
        <h2><a href="{quote(url)}">{escape(note.title)}</a></h2>
        <p>{escape(note.description)}</p>
        <a class="text-link" href="{quote(url)}">Read note <span aria-hidden="true">→</span></a>
      </article>''')
    listing = '\n'.join(entries) if entries else '<p class="note-empty-message">No posts yet.</p>'
    content = f'''  <main id="main-content" class="page-shell inner-page notes-page">
    <header class="page-intro notes-intro">
      <p class="eyebrow"><span></span> Notes</p>
      <h1>Notes</h1>
    </header>
    <section class="note-list" aria-label="Notes">
{listing}
    </section>
  </main>'''
    outputs[root / 'notes.html'] = render_page(template, 'Notes',
        'Notes and writing from Caio Azevedo on autonomous systems, machine learning, and research practice.',
        '.', content, 'notes.html', any(note.draft for note in notes))
    # Parse and render everything before changing output files.
    for path, html in outputs.items():
        if path != root / 'notes.html' and path.exists() and not path.read_text().startswith(GENERATED):
            raise ValueError(f'{path}: refusing to overwrite a hand-written HTML page.')
    for path, html in outputs.items():
        if not path.exists() or path.read_text() != html:
            path.write_text(html)
    # Remove only our generated pages when a note is renamed, deleted, or drafted.
    for path in (root / 'notes').rglob('*.html'):
        if path not in outputs and path.read_text().startswith(GENERATED):
            path.unlink()
    return len(notes)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--include-drafts', action='store_true', help='Include drafts for local review.')
    args = parser.parse_args()
    try:
        count = build(include_drafts=args.include_drafts)
    except (ValueError, OSError, yaml.YAMLError) as error:
        parser.exit(1, f'{error}\n')
    print(f'Built {count} note(s) and notes.html.')
